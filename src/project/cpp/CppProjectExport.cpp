            text += "// the arguments an automated smoke test needs. Replace the body with your\n";
            text += "// game; keep the loader call.\n";
            text += "//\n";
            text += "// Nothing here refers to CNA Studio. That is the point: this project builds\n";
            text += "// and ships on a machine that has never had Studio installed.\n";
            text += "\n";
            text += "#include <cstdlib>\n";
            text += "#include <exception>\n";
            text += "#include <filesystem>\n";
            text += "#include <iostream>\n";
            text += "#include <memory>\n";
            text += "#include <string>\n";
            text += "\n";
