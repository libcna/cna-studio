        /**
         * @brief Writes @p contents to @p path, creating parent directories.
         *
         * @param path Absolute destination.
         * @param contents Bytes to write.
         * @param errorMessage Filled in on failure.
         * @return Whether the file was written.
         */
        bool writeFile(const std::filesystem::path& path,
                       std::string_view contents,
                       std::string& errorMessage)
        {
            std::error_code code;
            std::filesystem::create_directories(path.parent_path(), code);
            if (code)
            {
                errorMessage = "cannot create '" + path.parent_path().generic_string()
                             + "': " + code.message();
                return false;
            }

            // Binary, deliberately. A source file written in text mode on Windows gets CRLF line
            // endings it did not have in Studio's tree, which is a diff nobody made and, for the
            // embedded runtime, a file that no longer matches the one it was embedded from.
            std::ofstream stream{path, std::ios::binary | std::ios::trunc};
            if (!stream)
            {
                errorMessage = "cannot write '" + path.generic_string() + "'";
                return false;
            }

            stream.write(contents.data(), static_cast<std::streamsize>(contents.size()));
            if (!stream)
            {
                errorMessage = "failed while writing '" + path.generic_string() + "'";
                return false;
            }
            return true;
        }

        /** @brief The CMake source-file list for whatever of the runtime must be compiled. */
        std::string runtimeCompiledSourceList()
        {
            std::string list;
            for (const StudioRuntimeSource& source : studioRuntimeSources())
            {
                if (!source.compiled) { continue; }
                list += "    " + std::string{source.pathInProject} + "\n";
            }
            return list;
        }

        /**
         * @brief The exported project's own CMakeLists.txt.
         *
         * It asks for exactly one thing the machine must already have: a CNA source checkout. CNA
         * installs no package configuration and exports no targets, so `find_package(CNA)` is not
         * available to write -- `add_subdirectory` on a checkout is the only way anything consumes
         * CNA today. Recorded as a CNA gap (G-09) rather than worked around silently, and the
         * generated file says so where the person who has to supply the path will read it.
         */
        /** @brief One directory the build copies beside the executable. */
        struct ContentStaging
        {
            /** @brief Project-relative source directory. */
            std::string from;
            /** @brief Destination, relative to the directory the executable lands in. */
            std::string to;
        };

        std::string cmakeListsFor(const std::string& targetName,
                                  const StudioTargetProfile& profile,
                                  const std::vector<ContentStaging>& staging,
                                  ProjectKind kind)
        {
            std::string text;
            text += "# Generated by CNA Studio. This is an ordinary CNA project: it needs CMake, a\n";
            text += "# C++23 compiler and a CNA checkout, and nothing else. CNA Studio does not have\n";
            text += "# to be installed to build or run this game, and nothing here refers to it.\n";
            text += "#\n";
            text += "# Edit it freely. Studio will not rewrite this file behind you -- re-exporting\n";
            text += "# into a directory that already has one requires asking for it explicitly.\n";
            text += "cmake_minimum_required(VERSION 3.20)\n";
            text += "project(" + targetName + " LANGUAGES CXX)\n\n";
            text += "set(CMAKE_CXX_STANDARD 23)\n";
            text += "set(CMAKE_CXX_STANDARD_REQUIRED ON)\n\n";
            text += "# Where CNA is. Pass -DCNA_ROOT=/path/to/cna, or set it in the environment.\n";
            text += "# CNA ships no installed package configuration and exports no targets, so\n";
            text += "# add_subdirectory on a source checkout is how everything consumes it today --\n";
            text += "# including CNA Studio itself. When CNA gains a find_package(CNA), this becomes\n";
            text += "# two lines shorter and stops needing a path at all.\n";
            text += "if(NOT CNA_ROOT AND DEFINED ENV{CNA_ROOT})\n";
            text += "    set(CNA_ROOT \"$ENV{CNA_ROOT}\")\n";
            text += "endif()\n";
            text += "if(NOT CNA_ROOT)\n";
            text += "    message(FATAL_ERROR\n";
            text += "        \"CNA_ROOT is not set. Point it at a CNA checkout:\\n\"\n";
            text += "        \"  cmake -S . -B build -DCNA_ROOT=/path/to/cna\")\n";
            text += "endif()\n";
            text += "if(NOT EXISTS \"${CNA_ROOT}/CMakeLists.txt\")\n";
            text += "    message(FATAL_ERROR \"CNA_ROOT='${CNA_ROOT}' is not a CNA checkout.\")\n";
            text += "endif()\n\n";
            text += "# How this project was authored to build. Every one of these is an ordinary\n";
            text += "# CNA configure option, and every one is overridable on the command line: a\n";
            text += "# game builds for whatever its builder selects, not for whatever the machine\n";
            text += "# that exported it happened to have. They are written as cache entries rather\n";
            text += "# than plain variables for exactly that reason.\n";
            for (const std::string& argument : studioTargetProfileCMakeArguments(profile))
            {
                // -DNAME=VALUE, as the build runner would pass it. Rendered here as the cache
                // entry that means the same thing, so the exported build and the one Studio runs
                // configure CNA identically -- and so a feature added to the profile model appears
                // in exported projects without anybody remembering to add it here too.
                const std::size_t equals = argument.find('=');
                if (equals == std::string::npos || argument.rfind("-D", 0) != 0) { continue; }

                const std::string name = argument.substr(2, equals - 2);
                const std::string value = argument.substr(equals + 1);
                if (name == "CMAKE_BUILD_TYPE")
                {
                    // Guarded: a multi-configuration generator picks the configuration at build
                    // time, and forcing this there is how a Debug build silently comes out Release.
                    text += "if(NOT CMAKE_CONFIGURATION_TYPES AND NOT CMAKE_BUILD_TYPE)\n";
                    text += "    set(CMAKE_BUILD_TYPE \"" + value + "\" CACHE STRING \"Build configuration\")\n";
                    text += "endif()\n";
                    continue;
                }
                text += "set(" + name + " \"" + value + "\" CACHE STRING \"Set by CNA Studio's export\")\n";
            }
            text += "\n";
            text += "# CNA builds its own test suite and its example programs by default, even when\n";
            text += "# it is consumed as a subdirectory rather than built on its own: neither option\n";
            text += "# is guarded by a top-level-project check. A game that only wants to *use* CNA\n";
            text += "# would compile the engine's whole test suite and every demo into its own build.\n";
            text += "#\n";
            text += "# Worse than slow: on a checkout without initialised submodules the tests fail\n";
            text += "# the configure outright looking for googletest, and CNA's examples resolve a\n";
            text += "# helper script through CMAKE_SOURCE_DIR -- which, from a subdirectory, is *this*\n";
            text += "# project's root, not CNA's -- so they cannot build from here at all.\n";
            text += "#\n";
            text += "# Cache entries, so you can turn either back on if you want them.\n";
            text += "set(CNA_BUILD_TESTS OFF CACHE BOOL \"Build CNA's own test suite\")\n";
            text += "set(CNA_BUILD_EXAMPLES OFF CACHE BOOL \"Build CNA's example programs\")\n\n";
            text += "add_subdirectory(\"${CNA_ROOT}\" \"${CMAKE_BINARY_DIR}/cna\")\n\n";
            // An XNA-compatible project has no scenes, so it is not given the scene runtime: a
            // game whose structure is its own would be compiling a loader for a format it never
            // reads, and a file it has no reason to keep is a file somebody has to wonder about.
            if (kind == ProjectKind::XnaCompatible)
            {
                text += "add_executable(" + targetName + " Source/Main.cpp)\n\n";
                text += "target_link_libraries(" + targetName + " PRIVATE CNA)\n\n";
            }
            else
            {
                text += "# The scene runtime, compiled as part of the game. It is project-owned source,\n";
                text += "# not a library the build machine is expected to have: see Runtime/README.md.\n";
                text += "add_executable(" + targetName + "\n";
                text += "    Source/Main.cpp\n";
                text += runtimeCompiledSourceList();
                text += ")\n\n";
                text += "target_include_directories(" + targetName + " PRIVATE Runtime/include)\n";
                text += "target_link_libraries(" + targetName + " PRIVATE CNA)\n\n";
            }
            text += "# Content sits beside the executable so the game finds it with a relative path\n";
            text += "# whatever directory it is launched from.\n";
            text += "add_custom_command(TARGET " + targetName + " POST_BUILD\n";
            for (const ContentStaging& directory : staging)
            {
                text += "    COMMAND \"${CMAKE_COMMAND}\" -E copy_directory\n";
                text += "            \"${CMAKE_CURRENT_SOURCE_DIR}/" + directory.from + "\"\n";
                text += "            \"$<TARGET_FILE_DIR:" + targetName + ">/" + directory.to + "\"\n";
            }
            text += "    COMMENT \"Staging content beside the executable\")\n";
            return text;
        }

        /** @brief The game's `main`: load the startup scene, draw it, and be testable doing it. */
