            text += "            scene_ = std::move(result.scene);\n";
            text += "            entities_ = scene_.getEntities().size();\n";
            text += "            loaded_ = true;\n";
            text += "        }\n";
            text += "\n";
            text += "        void Update(Xna::GameTime& gameTime) override\n";
            text += "        {\n";
            text += "            Game::Update(gameTime);\n";
            text += "            ++frames_;\n";
            text += "            if (frameLimit_ > 0 && frames_ >= frameLimit_) { Exit(); }\n";
